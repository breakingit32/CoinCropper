// Writes mobile/secrets.local.json into the APK's web files as builtin.local.js,
// so the app starts with your CCE login and API keys filled in.
// Run after `cap sync` (npm run apk does). The JSON file is git-ignored.
//
// secrets.local.json:
//   { "cceUser": "...", "ccePass": "...", "pcgsTokens": ["key1", "key2"],
//     "cacgKey": "...", "cacgToken": "...", "gsKey": "...", "gsToken": "...", "ngcToken": "..." }
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "..", "secrets.local.json");
const out = path.join(here, "..", "android", "app", "src", "main", "assets", "public", "builtin.local.js");
const KEYS = ["cceUser", "ccePass", "cceSearchUrl", "pcgsTokens", "cacgKey", "cacgToken", "gsKey", "gsToken", "ngcToken"];

let data = {};
if (fs.existsSync(src)) {
  const j = JSON.parse(fs.readFileSync(src, "utf8"));
  for (const k of KEYS) {
    let v = j[k];
    if (Array.isArray(v)) v = v.join("\n");
    if (typeof v === "string" && v.trim()) data[k] = v.trim();
  }
}
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `// Generated by mobile/scripts/bake-secrets.mjs. Do not commit.\nexport default ${JSON.stringify(data, null, 1)};\n`);
console.log(`built-in settings: ${Object.keys(data).join(", ") || "(none)"}`);
